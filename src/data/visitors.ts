/** Visitor weight is higher when the room has matching attractor tags. */
export function visitorWeight(visitor: VisitorDef, roomAttractTags: string[], roomId: string): number {
  let weight = 4 - visitor.rarity;
  if (visitor.rooms.includes(roomId as never)) weight += 3;
  if (roomAttractTags.some((tag) => visitor.lineKey.includes(tag))) weight += 1;
  if (roomAttractTags.includes('water') && ['duck', 'swan', 'otter', 'frog', 'turtle'].includes(visitor.species)) weight += 3;
  if (roomAttractTags.includes('bird') && ['bird', 'duck', 'swan', 'hen', 'owl'].includes(visitor.species)) weight += 3;
  if (roomAttractTags.includes('flower') && ['butterfly', 'bee'].includes(visitor.species)) weight += 4;
  if (roomAttractTags.includes('cosy') && ['cat', 'dog', 'rabbit'].includes(visitor.species)) weight += 2;
  if (roomAttractTags.includes('critter') && ['hedgehog', 'squirrel', 'butterfly', 'bee'].includes(visitor.species)) weight += 2;
  return Math.max(1, weight);
}
